/** `O` in a command is the user's own checkout, `@T` the temp folder; everything else is relative to the worktree. */
export function fillCase(command: string, dirs: { other: string; tempArea: string }): string {
  return command.replaceAll('O/', `${dirs.other}/`).replaceAll('@T', dirs.tempArea)
}
